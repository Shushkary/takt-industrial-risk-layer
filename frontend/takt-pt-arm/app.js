function drillIntoGroup(group) {
  queueDrill = {
    asset: group.primary_asset_id || '',
    operation: group.trigger_operation || '',
    riskClass: group.risk_class || '',
    label: `${group.trigger_operation || '—'} · ${group.primary_asset_id || `${group.assets} ${plural(group.assets, 'актив', 'актива', 'активов')}`} · ${term('risk_class', group.risk_class)}`,
    topCaseId: group.top_case_id || '',
  };
  queueMode = 'cases';
  try {
    localStorage.setItem(QUEUE_MODE_STORAGE, 'cases');
  } catch (error) {
    // Без хранилища выбор действует до перезагрузки.
  }
  applyQueueMode();
  lastQueueSignature = null;
  refresh().then(() => {
    if (queueDrill && queueDrill.topCaseId) openCase(queueDrill.topCaseId);
  });
}

function queueQueryString() {
  const params = new URLSearchParams({ sort: 'risk_score_desc', limit: String(QUEUE_PAGE_LIMIT) });
  const risk = $('#queueRisk').value;
  const status = $('#queueStatus').value;
  const search = $('#queueSearch').value.trim();
  if (risk) params.set('risk_classes', risk);
  if (status) params.set('status', status);
  // Поле поиска раньше умело только заголовок, и подпись об этом честно предупреждала.
  // Идентификатор дела и актив продукт ищет сам — отдельными параметрами запроса.
  if (search) {
    const field = $('#queueSearchField').value;
    if (field === 'case_id') params.set('case_id_prefix', search);
    else if (field === 'asset') params.set('primary_asset_id', search);
    else params.set('title_contains', search);
  }
  // Отбор из сведённой строки: актива и операции в видимых фильтрах нет, и подменять ими
  // подпись поля поиска значило бы обещать поиск, которого там не происходит.
  if (queueDrill) {
    if (queueDrill.asset) params.set('primary_asset_id', queueDrill.asset);
    if (queueDrill.operation) params.set('trigger_operation_contains', queueDrill.operation);
    if (queueDrill.riskClass) params.set('risk_classes', queueDrill.riskClass);
  }
  return params.toString();
}

async function refresh() {
  try {
    if (queueMode !== 'cases') {
      await refreshGroups();
      setConnection('ok');
      $('#lastSync').textContent = `обновлено ${utc(new Date().toISOString()).slice(11)} ${zoneLabel()}`;
      return;
    }
    const { data, headers } = await apiWithHeaders(`/cases?${queueQueryString()}`);
    cases = Array.isArray(data) ? data : data.items || [];
    renderQueue();
    const total = headers.get('X-Total-Count');
    $('#queueCount').textContent =
      total !== null ? `Показано ${cases.length} из ${total}` : `Показано ${cases.length}`;
    setConnection('ok');
    // Только время: дата опроса — это «сегодня», и в шапке она занимает место, вытесняя
    // состояние связи на вторую строку.
    $('#lastSync').textContent = `обновлено ${utc(new Date().toISOString()).slice(11)} ${zoneLabel()}`;
    // Опрос обновляет только очередь; открытая карточка кейса иначе могла молча устареть.
    // Сравнение — по сводке из той же очереди, полная перерисовка карточки произошла бы
    // резко под курсором аналитика и сбросила бы прокрутку/отметки в пакете реагирования.
    if (selectedCaseId) {
      const openSummary = cases.find((item) => item.case_id === selectedCaseId);
      if (openSummary) {
        const stale = openSummary.status !== currentCaseStatus || Number(openSummary.event_count) !== currentCaseEventCount;
        $('#staleCaseBanner').hidden = !stale;
      }
    }
    if (!selectedCaseId && cases.length) {
      const top = [...cases].sort(compareByRisk)[0];
      openCase(top.case_id);
    }
    return;
  } catch (error) {
    if (error.status === 401) {
      setConnection('auth');
      // Форма открывается один раз: повторный опрос не должен отбирать фокус у аналитика,
      // который в этот момент вводит ключ.
      if (!accessKeyPromptShown) {
        accessKeyPromptShown = true;
        openAccessKeyForm();
      }
    } else {
      setConnection('off', error.message);
    }
  }
}

