const FOCUSABLE_SELECTOR =
  'a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])';

function openModal(title, fill) {
  lastFocused = document.activeElement;
  $('#modalTitle').textContent = title;
  const body = $('#modalBody');
  body.replaceChildren();
  fill(body);
  $('#modal').hidden = false;
  // Фон под окном не прокручивается: иначе аналитик закрывает окно и не находит строку,
  // ради которой его открывал.
  document.body.classList.add('modal-open');
  $('#modalClose').focus();
}

function closeHelp() {
  $('#modal').hidden = true;
  document.body.classList.remove('modal-open');
  if (lastFocused && typeof lastFocused.focus === 'function') lastFocused.focus();
  lastFocused = null;
}

// Tab по кругу внутри окна. Без ловушки фокус уходит на очередь и таблицу за подложкой:
// с клавиатуры окно выглядит незакрытым, а нажатия попадают не туда.
function trapFocus(event) {
  const items = [...$('#modal').querySelectorAll(FOCUSABLE_SELECTOR)];
  if (!items.length) return;
  const first = items[0];
  const last = items[items.length - 1];
  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
}

// Порядок разделов записи неизменен: что это — откуда — что делать.
const HELP_SECTIONS = [
  ['what', 'Что это'],
  ['source', 'Откуда'],
  ['action', 'Что делать'],
];

// База адресов документации. Документы лежат в репозитории рядом с продуктом; на стенде их
// раздаёт тот же сервер, на боевом контуре база задаётся через window.TAKT_DOCS_BASE до
// загрузки сборки.
const DOCS_BASE = String(window.TAKT_DOCS_BASE || './').replace(/\/*$/, '/');

function openHelp(key) {
  const entry = HELP[key];
  if (!entry) return;
  openModal(entry.title, (body) => {
    for (const [field, heading] of HELP_SECTIONS) {
      if (!entry[field]) continue;
      const caption = document.createElement('h4');
      caption.className = 'modal-section';
      caption.textContent = heading;
      body.appendChild(caption);
      const text = document.createElement('p');
      text.textContent = entry[field];
      body.appendChild(text);
      // Шаги идут сразу за ответом «что это»: алгоритм — это порядок, и нумерация должна
      // держаться разметкой, а не цифрами, набранными внутри абзаца.
      if (field === 'what' && Array.isArray(entry.steps)) {
        const list = document.createElement('ol');
        list.className = 'modal-steps';
        for (const step of entry.steps) {
          const item = document.createElement('li');
          item.textContent = step;
          list.appendChild(item);
        }
        body.appendChild(list);
      }
    }
    if (!entry.doc) return;
    // Путь к документу раньше стоял простым текстом внутри абзаца: прочитать можно, открыть
    // нечем. Ссылка выносится в подвал окна, одна на запись.
    const footer = document.createElement('p');
    footer.className = 'modal-doc';
    const link = document.createElement('a');
    link.href = `${DOCS_BASE}${entry.doc}`;
    link.target = '_blank';
    link.rel = 'noopener';
    link.textContent = entry.doc;
    footer.append('Документ-источник: ', link);
    body.appendChild(footer);
  });
}

// Первое предложение записи. Точка внутри числа («1.00») концом предложения не считается:
// признак конца — точка перед пробелом и заглавной буквой или кавычкой, либо конец строки.
function firstSentence(text) {
  const match = String(text || '').match(/^.*?[.!?](?=\s+[«А-ЯЁA-Z]|$)/);
  return match ? match[0] : String(text || '');
}

// Короткая подсказка при наведении на «?». Иначе всякий вопрос стоит двух действий —
// открыть окно и закрыть его, — а таких кнопок на странице тридцать пять.
function fillHelpHints() {
  for (const button of document.querySelectorAll('[data-help]')) {
    const entry = HELP[button.dataset.help];
    if (entry) button.title = firstSentence(entry.what);
  }
}

function toast(message) {
  const box = $('#toast');
  box.textContent = message;
  box.hidden = false;
  setTimeout(() => {
    box.hidden = true;
  }, 4000);
}

