"""Измеренные векторы модели риска: сохранение при оценке и перенос в собранный инцидент.

Модель `Risk = F(R, G, C, U, DQ)` считает пять векторов. Часть из них — **измерения** по
самому событию (ритм опроса, организационный контекст, качество данных), часть поднимается
**срабатываниями инвариантов**. Правило их сложения одно и живёт в
`takt.domain.invariants.evaluator.risk_vectors_from_invariants`: базовые значения приходят из
измерений, срабатывания могут их только поднять.

Сборка инцидента это правило нарушала: она пересчитывала векторы по объединению срабатываний,
не передавая измеренную основу. На демонстрационном INC-002 объединение трёх инвариантов по
41 событию давало 0.324 против 0.467 у одного входящего в него срабатывания, и итог держался
только страховкой «не ниже худшей части». То есть сборка инцидента не добавляла к оценке
ничего, хотя её смысл — ровно обратный: канал управления, перемещение между узлами и работа
вне смены по отдельности слабы, вместе складываются в картину атаки.

Здесь только перенос уже измеренных значений. Ни новых весов, ни новых порогов, ни изменений
в самой `combine_risk` этот модуль не вводит.
"""

from __future__ import annotations

from collections.abc import Iterable

from takt.domain.engines.risk_engine import RiskBreakdown
from takt.domain.entities.case import Case

VECTOR_NAMES: tuple[str, ...] = ("rhythm", "graph", "context", "user", "data_quality")


def vectors_to_dict(breakdown: RiskBreakdown) -> dict[str, float]:
    """Векторы в вид, пригодный для хранения рядом с делом."""
    return {name: float(getattr(breakdown, name)) for name in VECTOR_NAMES}


def measured_base(cases: Iterable[Case], name: str) -> float:
    """Наибольшее измеренное значение вектора среди вошедших в инцидент дел.

    Максимум, а не среднее: инцидент не бывает спокойнее своей самой тревожной части, и это
    та же логика, по которой итог сборки не опускается ниже худшего из вошедших дел.
    """
    values = [float(case.risk_vectors.get(name, 0.0)) for case in cases if case.risk_vectors]
    return max(values, default=0.0)
