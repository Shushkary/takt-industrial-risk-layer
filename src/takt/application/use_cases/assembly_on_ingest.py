"""Сборка инцидента по мере приёма потока.

Отбирать отличительные сущности продукт научился сам (`auto_assemble_incidents`), но
запускался этот шаг только по команде: кнопкой «Собрать инциденты» в АРМ или в конце
пакетной загрузки датасета. Приём через API — тот путь, которым события приходят из SIEM,
EDR и NDR, — заканчивался лентой мелких дел конвейера, и на вопрос «что происходит после
загрузки потока» честный ответ оставался прежним: ничего, пока аналитик не нажмёт.

Этот триггер закрывает разрыв: событие, принятое штатным путём, само доводит поток до
инцидента.

**Запуск — по срабатыванию инварианта, а не по каждому событию.** Разбор начинается там,
где средство обнаружения или инвариант объявили аномалию. Замер на эталоне INC-002:
1030 событий, из них 19 со срабатыванием; приём стоит 30,5 с, все 19 прогонов сборки —
1,2 с, то есть 4 % сверху. Прогон по каждому событию стоил бы 65 с — вдвое дороже самого
приёма и ни одного нового инцидента.

**Результат совпадает с прогоном в конце.** Сборка по ходу потока не «примерно такая же»:
на INC-002 она даёт тот же инцидент из 23 событий цепочки без единого фонового, что и один
прогон после загрузки (`tests/test_assembly_on_ingest.py`). Совпадение держится двумя
свойствами `AutoAssembleIncidentsUseCase`: встречаемость сущностей пересчитывается на
каждом прогоне, а редакции, которых прогон на выросшем потоке не воспроизвёл, снимаются.
Без первого инцидент тянет 24 фоновых события, без второго рядом с ним остаётся карточка
из 12 событий чистого фона — оба числа измерены.

**Ограничение, которое нельзя обойти планировщиком.** Отличительность считается по уже
принятому потоку, поэтому редакция инцидента отражает то, что известно на момент
срабатывания. События цепочки, пришедшие после последнего срабатывания, попадут в инцидент
на следующем прогоне — или не попадут вовсе, если поток замолчал. Это свойство потоковой
сборки, а не дефект реализации: инцидент здесь — производная от принятого потока, а не
однажды сделанная запись.

**Часов здесь нет.** Момент прогона задаётся счётчиком срабатываний, а не таймером и не
паузой в потоке: иначе один и тот же поток, поданный быстрее или медленнее, давал бы разные
инциденты. Повторный приём тех же событий в том же порядке даёт тот же результат — это то же
требование воспроизводимости, что и у контура вердикта
(`tests/test_verdict_determinism_guard.py`).

Границы продукта не двигаются: сборка группирует уже принятые события. Вердикт, расширение
разбора до уровня узла и пакет реагирования остаются за аналитиком.
"""

from __future__ import annotations

import threading
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field

from takt.application.use_cases.auto_assemble_incidents import (
    AutoAssembleIncidentsUseCase,
    AutoAssemblyReport,
)


@dataclass(slots=True)
class AssembleOnIngest:
    """Запускает сборку инцидентов по ходу приёма событий."""

    assemble: AutoAssembleIncidentsUseCase
    # Сколько срабатываний накопить перед прогоном. 1 — инцидент появляется сразу за
    # аномалией; замер выше показывает, что это по карману. Значение выше единицы — для
    # инсталляций, где полный обход хранилища дел дороже (8000 дел — 1,8 с на прогон).
    hits_between_runs: int = 1
    actor: str = "ingest"
    # Куда сообщить о сбое сборки. Приём события первичен: инцидент — производная от
    # принятых событий, и несобранный инцидент не повод потерять событие.
    on_error: Callable[[BaseException], None] | None = None
    runs: int = field(default=0, init=False)
    last_report: AutoAssemblyReport | None = field(default=None, init=False)
    _pending: int = field(default=0, init=False, repr=False)
    # Приём идёт из нескольких обработчиков сразу (часть маршрутов FastAPI выполняется в
    # пуле потоков), а прогон читает и переписывает хранилище дел целиком. Замок удерживается
    # на всё время прогона, и это осознанная плата: два одновременных прогона переписывали бы
    # одни и те же дела, а приём события подождать может — событие уже сохранено.
    _lock: threading.Lock = field(default_factory=threading.Lock, init=False, repr=False)

    def after_ingest(self, *, invariant_hits: Sequence[str]) -> None:
        """Вызывается конвейером приёма после того, как событие принято и сохранено."""
        if not invariant_hits:
            return
        with self._lock:
            self._pending += 1
            if self._pending < max(1, self.hits_between_runs):
                return
            self._pending = 0
            self.runs += 1
            try:
                self.last_report = self.assemble.execute(actor=self.actor)
            except Exception as exc:
                if self.on_error is not None:
                    self.on_error(exc)
